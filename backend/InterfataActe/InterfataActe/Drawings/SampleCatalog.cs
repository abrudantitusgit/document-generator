        private static Proiect Br(long nr, string denumire, string tensiune, double pi, double pa, string punct, string cablu, long lungime)
        {
            var c = Client("Client Exemplu " + nr, "Oradea");
            var p = new Proiect
            {
                ID = Guid.NewGuid(), NrProiect = nr, Denumire = denumire, TensiuneUtilizare = tensiune, Pi = pi, Pa = pa,
                Data = new DateTime(2026, 10, 1), Client = c, ClientID = c.ID, LocConsum = "locuință",
                Judet = "Bihor", Localitatea = "Oradea", Strada = "Ceyrat", NrStrada = nr.ToString(),
            };
            p.Atr = new Atr
            {
                ID = Guid.NewGuid(), ProiectID = p.ID, NrAtr = 70000 + nr, DataAtr = new DateTime(2026, 9, 15),
                PunctRacordare = "LEA 0,4 kV PTA 12 Oradea", PunctAlimentare = "nr. 14 LEA 0,4 kV", PunctBransament = punct,
                Cablu = cablu, LungimeCablu = lungime, Ohmi = 4, Contor = tensiune.Contains("400") ? "electronic trifazat" : "electronic monofazat",
            };
            return p;
        }

