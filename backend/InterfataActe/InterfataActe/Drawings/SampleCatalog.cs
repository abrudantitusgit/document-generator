        public static int Generate(string root, DrawingService service)
        {
            var readme = new StringBuilder();
            readme.AppendLine("# generatedDraws");
            readme.AppendLine();
            readme.AppendLine("Sample drawings generated by `InterfataActe` for every use case, one folder per use case.");
            readme.AppendLine("Each drawing is written in all formats: " + string.Join(", ", service.Formats.Select(f => "`" + f + "`")) + ".");
            readme.AppendLine("The same files are written for real projects into `<proiect>/generatedDraws/` when documents are generated.");
            readme.AppendLine();
            readme.AppendLine("Regenerate (from `backend/InterfataActe/InterfataActe`): `dotnet run -- --generate-samples ../../../generatedDraws`");
            readme.AppendLine();
            readme.AppendLine("| Use case | Folder | Condition | Drawings | Sample |");
            readme.AppendLine("|---|---|---|---|---|");

            int failures = 0;
            foreach (var (expected, project) in Fotovoltaice())
            {
                var uc = service.UseCase(project);
                failures += Check(expected, uc.Code);
                var drawings = service.Build(project);
                var folder = Path.Combine(root, DrawingUseCaseResolver.Fotovoltaice, uc.Code);
                failures += Report(service.Write(drawings, folder, true));
                readme.AppendLine($"| {uc.Code} | `{DrawingUseCaseResolver.Fotovoltaice}/{uc.Code}` | {uc.Description} | {string.Join(", ", drawings.Select(d => $"{d.Code} {d.Title}"))} | " +
                    $"{project.TipSistem}, {project.DatePanouri.Sum(p => p.NrPanouri)} panouri, {DrawingContext.Num(project.PutereTotalaPanouri / 1000)} kWp, {project.DateInvertoare.Sum(i => i.NrInvertoare)} invertor(oare){(project.CapacitateTotalaBaterii != 0 ? ", baterie" : "")} |");
            }
            foreach (var (expected, project) in Bransamente())
            {
                var uc = service.UseCase(project);
                failures += Check(expected, uc.Code);
                var drawings = service.Build(project);
                var folder = Path.Combine(root, DrawingUseCaseResolver.Bransamente, uc.Code);
                failures += Report(service.Write(drawings, folder, true));
                readme.AppendLine($"| {uc.Code} | `{DrawingUseCaseResolver.Bransamente}/{uc.Code}` | {uc.Description} | {string.Join(", ", drawings.Select(d => $"{d.Code} {d.Title}"))} | " +
                    $"{project.Atr.PunctBransament}, cablu {project.Atr.Cablu}, Pi = {DrawingContext.Num(project.Pi)} kW |");
            }

            readme.AppendLine();
            readme.AppendLine("Use-case rules: `backend/InterfataActe/InterfataActe/Drawings/Model/DrawingUseCaseResolver.cs`.");
            readme.AppendLine("Layers (identical names in DXF, draw.io and SVG): " + string.Join(", ", Core.Layers.All.Select(l => $"`{l.Name}`")) + ".");
            File.WriteAllText(Path.Combine(root, "README.md"), readme.ToString());
            Console.WriteLine(failures == 0 ? $"Catalog generat in {root}" : $"Catalog generat cu {failures} erori");
            return failures == 0 ? 0 : 1;
        }

        private static int Check(string expected, string actual)
        {
            if (expected == actual) return 0;
            Console.WriteLine($"EROARE: proiectul de test pentru {expected} a fost clasificat ca {actual}");
            return 1;
        }

        private static int Report(DTO.GenerateResult result)
        {
            foreach (var m in result.Messages) Console.WriteLine(m);
            return result.Success ? 0 : 1;
        }

        private static Client Client(string nume, string localitatea) => new()
        {
            ID = Guid.NewGuid(), Nume = nume, CNP = 1800101050000, Judet = "Bihor", Localitatea = localitatea,
            Strada = "Exemplu", NrStrada = "1", Telefon = "0700000000",
        };

        private static ProiectFotovoltaice Pv(long nr, string tip, string client, string firma, string localitate, string strada, string nrStrada)
        {
            var c = Client(client, localitate);
            return new ProiectFotovoltaice
            {
                ID = Guid.NewGuid(), NrProiect = nr, NrPV = nr, Data = new DateTime(2026, 10, 1), TipSistem = tip,
                Client = c, ClientID = c.ID,
                Firma = firma == null ? null : new Firma { ID = Guid.NewGuid(), Nume = firma, ClientID = c.ID, CUI = 40000000, ORC = "J05/100/2020" },
                Judet = "Bihor", Localitatea = localitate, Strada = strada, NrStrada = nrStrada,
                Amplasare = "acoperiș casă", POD = "RO005E5" + nr.ToString("D11"), Backup = "-", SmartMeter = "-",
            };
        }

        private static DataPanou Panouri(string model, int nr, decimal w) => new() { Id = Guid.NewGuid(), Model = model, NrPanouri = nr, PutereInstalata = w, Serie = "-" };
        private static DataInvertor Invertor(string model, int nr, decimal kw) => new() { Id = Guid.NewGuid(), Model = model, NrInvertoare = nr, PutereInstalata = kw, Serie = "-" };
